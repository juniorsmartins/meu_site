import { z } from 'zod';
import { MENSAGENS_ERRO } from '../configs/mensagensConfig.js';
import { FUNCOES_USUARIO, REGRAS_USUARIO } from "../configs/constantsConfig.js";

const FUNCOES_VALIDAS = Object.values(FUNCOES_USUARIO);

const usuarioCriarSchema = z.object({
    nome: z.string({ 
        message: MENSAGENS_ERRO.USUARIO.CAMPO_NOME_OBRIGATORIO 
    })
    .min(REGRAS_USUARIO.NOME.MIN, MENSAGENS_ERRO.USUARIO.CAMPO_NOME_MINIMO_CARACTERES(REGRAS_USUARIO.NOME.MIN))
    .max(REGRAS_USUARIO.NOME.MAX, MENSAGENS_ERRO.USUARIO.CAMPO_NOME_MAXIMO_CARACTERES(REGRAS_USUARIO.NOME.MAX))
    .trim(),

    email: z.string({ 
        message: MENSAGENS_ERRO.USUARIO.CAMPO_EMAIL_OBRIGATORIO 
    })
    .min(1, MENSAGENS_ERRO.USUARIO.CAMPO_EMAIL_OBRIGATORIO)
    .email(MENSAGENS_ERRO.USUARIO.CAMPO_EMAIL_FORMATO_INVALIDO)
    .lowercase()
    .trim(),

    senha: z.string({ 
        message: MENSAGENS_ERRO.USUARIO.CAMPO_SENHA_OBRIGATORIO 
    })
    .min(REGRAS_USUARIO.SENHA.MIN, MENSAGENS_ERRO.USUARIO.CAMPO_SENHA_MINIMO_CARACTERES(REGRAS_USUARIO.SENHA.MIN))
    .max(REGRAS_USUARIO.SENHA.MAX, MENSAGENS_ERRO.USUARIO.CAMPO_SENHA_MAXIMO_CARACTERES(REGRAS_USUARIO.SENHA.MAX)),

    funcao: z.enum(FUNCOES_VALIDAS)
    .optional()
});

const usuarioAtualizarSchema = z.object({
    nome: z.string()
    .min(REGRAS_USUARIO.NOME.MIN, MENSAGENS_ERRO.USUARIO.CAMPO_NOME_MINIMO_CARACTERES(REGRAS_USUARIO.NOME.MIN))
    .max(REGRAS_USUARIO.NOME.MAX, MENSAGENS_ERRO.USUARIO.CAMPO_NOME_MAXIMO_CARACTERES(REGRAS_USUARIO.NOME.MAX))
    .trim()
    .optional(),

    email: z.string()
    .email(MENSAGENS_ERRO.USUARIO.CAMPO_EMAIL_FORMATO_INVALIDO)
    .lowercase()
    .trim()
    .optional(),

    senha: z.string()
    .min(REGRAS_USUARIO.SENHA.MIN, MENSAGENS_ERRO.USUARIO.CAMPO_SENHA_MINIMO_CARACTERES(REGRAS_USUARIO.SENHA.MIN))
    .max(REGRAS_USUARIO.SENHA.MAX, MENSAGENS_ERRO.USUARIO.CAMPO_SENHA_MAXIMO_CARACTERES(REGRAS_USUARIO.SENHA.MAX))
    .optional(),

    funcao: z.enum(FUNCOES_VALIDAS)
    .optional()
});

export { 
    usuarioCriarSchema, 
    usuarioAtualizarSchema 
};

